#!/usr/bin/env python3
"""Generate the synthetic stress programs backing the RQ4 scaling/worst-case
evidence (paper/evaluation/rq4-stress.csv).

Usage: rq4-stress-gen.py <out-dir>

Writes, deterministically:

- normal_{64,256,1024}.cst -- "normal analysing at scale": N three-parameter
  helpers (a: num, b: const num, c: num) whose bodies chain into the previous
  helper with the chain depth capped at 64; main calls every helper once,
  alternating all-literal arguments (the call folds) and source()-fed
  arguments (the call residualizes). About half the calls fold, mirroring the
  suite's mix at up to ~30x the largest suite program.

- worst_{64,256,1024}.cst -- adversarial for the fused lower+fold phase: N
  helpers with four runtime-allowed parameters (a wide result-join to
  substitute and normalize per call), same depth-64-capped chaining, and main
  calls every helper with *distinct* literal arguments, so every call is
  classified C-CT and folded and no two calls share arguments. The residual
  program is a row of literals, so the fused phase's share of compiler work is
  maximized by construction.

- budget_trip.cst -- a single chain of 300 helpers called once at the head.
  This must FAIL to compile with the const-eval call-depth diagnostic; it is
  the evidence that a pathological fold is capped by the budgets of
  cstc_tyir_interp (step budget 4096, call depth 256) rather than silently
  consuming unbounded compile time.
"""

import sys
from pathlib import Path

SIZES = (64, 256, 1024)


def gen_normal(n: int) -> str:
    out = [
        "// AUTO-GENERATED by rq4-stress-gen.py -- do not edit by hand.",
        "// Scenario 'normal': mixed fold/residual chains at scale.",
        "runtime fn source() -> num { 1 }",
        "",
        "fn n_0(a: num, b: const num, c: num) -> num { a + b * 2 + c }",
    ]
    for i in range(1, n):
        body = "a + b * 2 + c" if i % 64 == 0 else f"a + b * 2 + c + n_{i - 1}(a, b, c)"
        out.append(f"fn n_{i}(a: num, b: const num, c: num) -> num {{ {body} }}")
    out.append("")
    out.append("fn main() {")
    for i in range(n):
        if i % 2 == 0:
            out.append(f"    let s{i}: num = n_{i}({i % 7 + 1}, {i % 5 + 1}, {i % 3 + 1});")
        else:
            out.append(f"    let r{i}: runtime num = n_{i}(source(), {i % 5 + 1}, {i % 3 + 1});")

    def val(i: int, a: int, b: int, c: int) -> int:
        v = a + b * 2 + c
        return v if i == 0 or i % 64 == 0 else v + val(i - 1, a, b, c)

    for i in range(0, n, 16):
        out.append(f"    assert_eq(s{i}, {val(i, i % 7 + 1, i % 5 + 1, i % 3 + 1)});")
    for i in range(2, n, 2):
        if i % 16 != 0:
            out.append(f"    let _ = s{i};")
    for i in range(1, n, 2):
        out.append(f"    let _ = r{i};")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_worst(n: int) -> str:
    out = [
        "// AUTO-GENERATED by rq4-stress-gen.py -- do not edit by hand.",
        "// Scenario 'worst': maximal fold density; every call folds, distinct",
        "// arguments at every call site, wide (4-parameter) result joins.",
        "fn w_0(p0: num, p1: num, p2: num, p3: num) -> num { p0 + p1 + p2 + p3 }",
    ]
    for i in range(1, n):
        body = (
            "p0 + p1 + p2 + p3"
            if i % 64 == 0
            else f"p0 + p1 + p2 + p3 + w_{i - 1}(p0, p1, p2, p3)"
        )
        out.append(
            f"fn w_{i}(p0: num, p1: num, p2: num, p3: num) -> num {{ {body} }}"
        )
    out.append("")
    out.append("fn main() {")

    def val(i: int, p0: int) -> int:
        v = p0 + 2 + 3 + 4
        return v if i == 0 or i % 64 == 0 else v + val(i - 1, p0)

    for i in range(n):
        out.append(f"    let x{i}: num = w_{i}({i + 1}, 2, 3, 4);")
    for i in range(0, n, 16):
        out.append(f"    assert_eq(x{i}, {val(i, i + 1)});")
    for i in range(n):
        if i % 16 != 0:
            out.append(f"    let _ = x{i};")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_budget_trip() -> str:
    out = [
        "// AUTO-GENERATED by rq4-stress-gen.py -- do not edit by hand.",
        "// Scenario 'budget_trip': a 300-deep chain folded at the head must",
        "// FAIL with the const-eval call-depth diagnostic (limit 256).",
        "fn d_0(x: num) -> num { x + 1 }",
    ]
    for i in range(1, 300):
        out.append(f"fn d_{i}(x: num) -> num {{ d_{i - 1}(x) + 1 }}")
    out += [
        "",
        "fn main() {",
        "    let v: num = d_299(1);",
        "    let _ = v;",
        "}",
    ]
    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} <out-dir>")
    out_dir = Path(sys.argv[1])
    out_dir.mkdir(parents=True, exist_ok=True)
    for n in SIZES:
        (out_dir / f"normal_{n}.cst").write_text(gen_normal(n))
        (out_dir / f"worst_{n}.cst").write_text(gen_worst(n))
    (out_dir / "budget_trip.cst").write_text(gen_budget_trip())
    for path in sorted(out_dir.glob("*.cst")):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
